# Generates raster_irq.prg (used by tests/cia_timing.rs). Run: python3 make_raster_irq_prg.py
code=bytearray(); ORG=0x0810
def b(*x): code.extend(x)
b(0x78)                                  # SEI
b(0xA9,0x7F,0x8D,0x0D,0xDC,0x8D,0x0D,0xDD,0xAD,0x0D,0xDC,0xAD,0x0D,0xDD)
b(0xA9,0x35,0x85,0x01)                   # RAM at E000-FFFF... keep IO
b(0xA9,0x0B,0x8D,0x11,0xD0)              # DEN off (no badlines), RSEL
b(0xA9,0x00,0x8D,0x15,0xD0)              # no sprites
b(0xA9,0x80,0x8D,0x12,0xD0)              # raster compare line $80
irq=ORG+0x40
b(0xA9,irq&0xFF,0x8D,0xFE,0xFF,0xA9,irq>>8,0x8D,0xFF,0xFF)
b(0xA9,0x01,0x8D,0x1A,0xD0)              # enable raster irq
b(0x8D,0x19,0xD0)                        # ack
b(0x58)                                  # CLI
loop=ORG+len(code); b(0x4C,loop&0xFF,loop>>8)   # JMP *
while len(code)<0x40: b(0xEA)
# irq handler at ORG+0x40: ack and RTI
b(0xEE,0x19,0xD0)                        # INC $D019
b(0x40)
stub=bytes([0x0B,0x08,0x0A,0x00,0x9E])+b'2064'+bytes([0,0,0])
prg=bytes([1,8])+stub+bytes(ORG-0x0801-len(stub))+bytes(code)
open('raster_irq.prg','wb').write(prg); print(hex(irq))
